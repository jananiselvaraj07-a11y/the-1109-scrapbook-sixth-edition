const timelineContainer = document.getElementById("timeline-container");

memories.forEach((memory) => {
  const item = document.createElement("div");
  item.className = "timeline-item";

  item.innerHTML = `
    <div class="timeline-dot"></div>
    <div class="memory-card" tabindex="0" role="button" aria-expanded="false">
      <span class="memory-date">${memory.date}</span>
      <h3>${memory.title}</h3>
      <p>${memory.preview}</p>
      <div class="memory-detail hidden">${memory.detail}</div>
      <p class="expand-label">Tap to open ♡</p>
    </div>
  `;

  const card = item.querySelector(".memory-card");
  const detail = item.querySelector(".memory-detail");
  const label = item.querySelector(".expand-label");

  function toggleMemory() {
    const isOpening = detail.classList.contains("hidden");
    detail.classList.toggle("hidden");
    label.textContent = isOpening ? "Tap to close ↑" : "Tap to open ♡";
    card.setAttribute("aria-expanded", String(isOpening));
  }

  card.addEventListener("click", toggleMemory);
  card.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      toggleMemory();
    }
  });

  timelineContainer.appendChild(item);
});

